/// 短い名前 `name` の正式な名前（表になければ `None`）
pub(super) fn long_name(name: &str) -> Option<&'static str> {
    SHORT_NAMES
        .binary_search_by(|&(short, _)| short.cmp(name))
        .ok()
        .and_then(|index| SHORT_NAMES.get(index))
        .map(|&(_, long)| long)
}

#[cfg(test)]
pub(super) fn pairs() -> &'static [(&'static str, &'static str)] {
    SHORT_NAMES
}
